"""
Monte Carlo experiment for Chapter 1 (Section "A Monte Carlo experiment").

What the cross-industry SCP regression L_k = b0 + b1 HHI_k + e_k recovers when the
industries are generated by known models.

Every simulated industry k has linear inverse demand P = a - b Q, constant marginal
cost c and a fixed (entry) cost F. Primitives are drawn independently:
    a ~ U[8, 12],  c ~ U[1, 4],  b ~ U[0.5, 2],  log F ~ U[log 0.1, log 10],
and draws are kept only if the Cournot free-entry number of firms is at least one,
i.e. x = (a - c) / sqrt(b F) >= 2.

Designs
    (1) Cournot, N ~ U{1, ..., 20} drawn independently of the primitives.
    (2) Cournot, free entry:     N* = x - 1 (continuous), HHI = 1/N*, L = m/(c + m),
                                 m = sqrt(b F) the free-entry dollar markup.
    (3) Collusion, free entry:   N^m = x^2 / 4, HHI = 4 / x^2, L = (a - c)/(a + c).
    (4) Mixed conduct, free entry: each industry colludes with probability 1/2.
    (5) Cost heterogeneity (Demsetz design): Cournot with N = 3 firms whose costs are
        c_i = cbar + lam (P0 - cbar) z_i, z = (-1, 0, 1), lam ~ U[0, 0.95]
        independent of (a, b, cbar), cbar ~ U[2.5, 4] (keeps every cost positive).
        P, Q and consumer surplus do not depend on lam; HHI and L rise with lam.
    (6) One primitive at a time (Cournot, free entry) through the base point
        (a, c, b, F) = (10, 2.5, 1.25, 1).

OLS with HC1 standard errors is computed by hand (numpy only).

Outputs (paths relative to Textbook/):
    figures/ch01/scp_montecarlo.pdf          six-panel figure
    figures/ch01/scp_montecarlo_table.tex    table fragment (pasted into the chapter)
    figures/ch01/src/scp_montecarlo_summary.json   numbers quoted in the text
"""
import os
import json
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
FIGDIR = os.path.dirname(HERE)

SEED = 20261022
NIND = 1000
rng = np.random.default_rng(SEED)

A_RNG = (8.0, 12.0)
C_RNG = (1.0, 4.0)
B_RNG = (0.5, 2.0)
F_RNG = (0.1, 10.0)        # log-uniform
NFIX_MAX = 20
P_COLLUDE = 0.5
N_DEMSETZ = 3
CBAR_RNG_DEMSETZ = (2.5, 4.0)
LAM_MAX = 0.95
BASE = dict(a=10.0, c=2.5, b=1.25, F=1.0)


# ------------------------------------------------------------------ primitives
def draw_primitives(n, rng):
    """Independent draws of (a, c, b, F), kept if x = (a - c)/sqrt(bF) >= 2."""
    keep = {k: [] for k in ("a", "c", "b", "F")}
    tried, accepted = 0, 0
    while accepted < n:
        m = 2 * (n - accepted) + 10
        a = rng.uniform(*A_RNG, m)
        c = rng.uniform(*C_RNG, m)
        b = rng.uniform(*B_RNG, m)
        F = np.exp(rng.uniform(np.log(F_RNG[0]), np.log(F_RNG[1]), m))
        ok = (a - c) / np.sqrt(b * F) >= 2.0
        tried += m
        idx = np.where(ok)[0][: n - accepted]
        # acceptance rate is computed on the draws actually examined
        last = idx[-1] + 1 if len(idx) == n - accepted else m
        tried -= (m - last)
        for k, v in zip(("a", "c", "b", "F"), (a, c, b, F)):
            keep[k].extend(v[idx].tolist())
        accepted += len(idx)
    return pd.DataFrame(keep), accepted / tried


# ------------------------------------------------------------------ models
def cournot_fixed(a, c, b, N):
    P = (a + N * c) / (N + 1.0)
    Q = N * (a - c) / (b * (N + 1.0))
    return dict(H=1.0 / N, L=(P - c) / P, P=P, Q=Q, N=N)


def cournot_free(a, c, b, F):
    x = (a - c) / np.sqrt(b * F)
    return cournot_fixed(a, c, b, x - 1.0)


def collusion_free(a, c, b, F):
    N = (a - c) ** 2 / (4.0 * b * F)
    P = (a + c) / 2.0 * np.ones_like(N)
    Q = (a - c) / (2.0 * b)
    return dict(H=1.0 / N, L=(P - c) / P, P=P, Q=Q, N=N)


def cournot_slope(a, c, H):
    """Derivative of the Cournot curve L(H) = (a - c) H / (a H + c) at H."""
    return c * (a - c) / (a * H + c) ** 2


def cs_ratio(Q, a, c, b):
    """Consumer surplus relative to its competitive level at (average) cost c."""
    Qc = (a - c) / b
    return (Q / Qc) ** 2


# ------------------------------------------------------------------ OLS + HC1
def ols_hc1(y, h):
    y = np.asarray(y, float)
    X = np.column_stack([np.ones_like(y), np.asarray(h, float)])
    n, k = X.shape
    XtX_inv = np.linalg.inv(X.T @ X)
    beta = XtX_inv @ X.T @ y
    e = y - X @ beta
    meat = (X * (e ** 2)[:, None]).T @ X
    V = XtX_inv @ meat @ XtX_inv * n / (n - k)
    tss = np.sum((y - y.mean()) ** 2)
    r2 = 1.0 - np.sum(e ** 2) / tss if tss > 1e-14 else float("nan")
    return dict(b0=float(beta[0]), se0=float(np.sqrt(V[0, 0])),
                b1=float(beta[1]), se1=float(np.sqrt(V[1, 1])), r2=float(r2),
                meanH=float(np.mean(h)), meanL=float(np.mean(y)), n=int(n))


# ------------------------------------------------------------------ simulate
prim, accept_rate = draw_primitives(NIND, rng)
a, c, b, F = (prim[k].to_numpy() for k in ("a", "c", "b", "F"))
Nfix = rng.integers(1, NFIX_MAX + 1, NIND).astype(float)
collude = rng.random(NIND) < P_COLLUDE
cbar5 = rng.uniform(*CBAR_RNG_DEMSETZ, NIND)
lam5 = rng.uniform(0.0, LAM_MAX, NIND)

d = {}
d[1] = cournot_fixed(a, c, b, Nfix)
d[2] = cournot_free(a, c, b, F)
d[3] = collusion_free(a, c, b, F)
d[4] = {k: np.where(collude, d[3][k], d[2][k]) for k in ("H", "L", "P", "Q", "N")}

# design 5: N = 3 Cournot firms with a mean-preserving spread of costs
z = np.linspace(-1.0, 1.0, N_DEMSETZ)                 # (-1, 0, 1), sums to zero
P5 = (a + N_DEMSETZ * cbar5) / (N_DEMSETZ + 1.0)      # price depends on sum of costs only
ci = cbar5[:, None] + lam5[:, None] * (P5 - cbar5)[:, None] * z[None, :]
assert np.all(ci > 0) and np.all(P5[:, None] - ci > 0)
qi = (P5[:, None] - ci) / b[:, None]                  # Cournot FOC: b q_i = P - c_i
Q5 = qi.sum(axis=1)
si = qi / Q5[:, None]
H5 = np.sum(si ** 2, axis=1)
L5 = np.sum(si * (P5[:, None] - ci) / P5[:, None], axis=1)
eps5 = P5 / (b * Q5)
assert np.allclose(L5, H5 / eps5)                     # Cowling-Waterson check
assert np.allclose(H5, 1.0 / N_DEMSETZ + lam5 ** 2 * np.sum(z ** 2) / N_DEMSETZ ** 2)
d[5] = dict(H=H5, L=L5, P=P5, Q=Q5, N=np.full(NIND, float(N_DEMSETZ)))

# consumer surplus relative to the competitive level at (average) marginal cost
csr = {1: cs_ratio(d[1]["Q"], a, c, b), 2: cs_ratio(d[2]["Q"], a, c, b),
       3: cs_ratio(d[3]["Q"], a, c, b)}
csr[4] = np.where(collude, csr[3], csr[2])
csr[5] = cs_ratio(Q5, a, cbar5, b)                    # = (N/(N+1))^2 for every industry

# average structural slope dL_k/dHHI at each industry's own HHI
sslope = {1: cournot_slope(a, c, d[1]["H"]), 2: cournot_slope(a, c, d[2]["H"]),
          3: np.zeros(NIND)}
sslope[4] = np.where(collude, 0.0, sslope[2])
sslope[5] = 1.0 / eps5            # L = HHI / eps with eps unchanged by the cost spread

# random-assignment benchmark: slope of the average structural function
# m(h) = (1/n) sum_k L_k(h) regressed on h, with h drawn from the design's own HHI
# distribution (what OLS would recover if HHI were assigned independently of k)
def cournot_curve(h):
    return (a[None, :] - c[None, :]) * h[:, None] / (a[None, :] * h[:, None] + c[None, :])


def ra_slope(H, m_of_h):
    m = m_of_h(H)
    return ols_hc1(m, H)["b1"]


ra = {}
ra[1] = ra_slope(d[1]["H"], lambda h: cournot_curve(h).mean(axis=1))
ra[2] = ra_slope(d[2]["H"], lambda h: cournot_curve(h).mean(axis=1))
ra[3] = 0.0                                   # L_k(h) does not depend on h
ra[4] = ra_slope(d[4]["H"], lambda h: np.where(collude[None, :], d[3]["L"][None, :],
                                               cournot_curve(h)).mean(axis=1))
ra[5] = ra_slope(d[5]["H"], lambda h: h * np.mean(1.0 / eps5))

reg = {j: ols_hc1(d[j]["L"], d[j]["H"]) for j in range(1, 6)}
reg_cs = {j: ols_hc1(csr[j], d[j]["H"]) for j in range(1, 6)}
for j in range(1, 6):
    reg[j]["avgderiv"] = float(np.mean(sslope[j]))
    reg[j]["ra"] = float(ra[j])
cs5_sd = float(np.std(csr[5]))

# mean of L given N in design (1), for the figure
cmean1 = pd.DataFrame({"N": Nfix, "L": d[1]["L"]}).groupby("N")["L"].mean()

# design (6): one primitive at a time, Cournot free entry, through BASE
grid = 400
paths = {}
for name, lo, hi, logscale in (("F", *F_RNG, True), ("b", *B_RNG, False),
                               ("a", *A_RNG, False), ("c", *C_RNG, False)):
    vals = np.exp(np.linspace(np.log(lo), np.log(hi), grid)) if logscale \
        else np.linspace(lo, hi, grid)
    p = {k: np.full(grid, v) for k, v in BASE.items()}
    p[name] = vals
    ok = (p["a"] - p["c"]) / np.sqrt(p["b"] * p["F"]) >= 2.0
    out = cournot_free(p["a"][ok], p["c"][ok], p["b"][ok], p["F"][ok])
    o = np.argsort(out["H"])
    paths[name] = (out["H"][o], out["L"][o])
base = cournot_free(BASE["a"], BASE["c"], BASE["b"], BASE["F"])

# design diagnostics quoted in the text
x_all = (a - c) / np.sqrt(b * F)
share_neg_profit_1 = float(np.mean(Nfix > x_all - 1.0))
share_LmGEc = float(np.mean(d[3]["L"] >= d[2]["L"] - 1e-12))
share_HmLEc = float(np.mean(d[3]["H"] <= d[2]["H"] + 1e-12))
corrs = np.corrcoef(np.column_stack([a, c, b, np.log(F)]).T)
max_corr = float(np.max(np.abs(corrs[np.triu_indices(4, 1)])))


